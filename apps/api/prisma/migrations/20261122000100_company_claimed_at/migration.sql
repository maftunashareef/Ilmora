-- №83 (перепроверка Шерзода 11.11, Нозим): у компании — когда запись занял нынешний представитель, как у учреждения
-- (Institution.claimedAt, #46). Сейчас «брошенный» черновик компании считается от создания записи или последнего
-- решения проверки; захватчик чужого СТИР, которого отвязали, через секунду забирал запись обратно у настоящей
-- компании — запись старше 14 дней, значит «брошена». Код будет считать срок от самой поздней из трёх дат.
-- Заполнение: у записей с представителем claimedAt = createdAt — дата, от которой срок считается сейчас, поэтому
-- никто не станет «брошенным» раньше прежнего. У свободных записей — пусто.
-- Совместимо с кодом прошлого релиза: новая необязательная колонка, старый код её не читает.
-- One transaction with a lock timeout (security review 11.11, №87 and №122; docs/migrations.md).
BEGIN;
SET LOCAL lock_timeout = '3s';

ALTER TABLE "Company" ADD COLUMN "claimedAt" TIMESTAMP(3);

UPDATE "Company" c SET "claimedAt" = c."createdAt"
WHERE EXISTS (SELECT 1 FROM "User" u WHERE u."companyId" = c."id");

COMMIT;
