-- «Разослать студентам»: фильтр по курсам необязателен (ТЗ «Студенты у компании, Вакансии у учреждения», 3.2; решение
-- владельца задачи). Пустой список курсов значит «все курсы»: вакансию получают все подтверждённые студенты выбранных
-- направлений, в том числе те, у кого курс в анкете не указан. До сих пор база требовала хотя бы один курс.
-- Проверка та же по имени, правило слабее: убрано только `cardinality("courses") >= 1`; список по-прежнему не NULL,
-- без пустых элементов, каждый курс от 1 до 11 (для пустого списка обе проверки `ALL` истинны).
-- Совместимо с кодом прошлого релиза: он всегда пишет хотя бы один курс, а ограничение только ослабляется — все
-- существующие строки и всё, что пишет старый код, проходят. При откате кода на эту схему: рассылку с пустым списком,
-- которую очередь ещё не доставила, старый код доставит никому (`course IN ()`) и закроет — лишнего никто не получит.
-- One transaction with a lock timeout (security review 11.11, №87 and №122; docs/migrations.md).
BEGIN;
SET LOCAL lock_timeout = '3s';

ALTER TABLE "VacancyBroadcast" DROP CONSTRAINT "VacancyBroadcast_courses_check";
ALTER TABLE "VacancyBroadcast" ADD CONSTRAINT "VacancyBroadcast_courses_check" CHECK (
  "courses" IS NOT NULL AND array_position("courses", NULL) IS NULL
  AND 1 <= ALL ("courses") AND 11 >= ALL ("courses")
);

COMMIT;
